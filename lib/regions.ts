const REGIONS_BY_COUNTRY: Record<string, { label: string; regions: Region[] }> = {
  'United States': { label: 'State', regions: US_STATES },
  Canada: { label: 'Province or Territory', regions: CANADA_PROVINCES },
  Australia: { label: 'State or Territory', regions: AUSTRALIA_STATES },
};

/** The state/province list for a country, or null when the country doesn't use one here. */
export function getRegionsForCountry(country: string | null | undefined) {
  return (country && REGIONS_BY_COUNTRY[country]) || null;
}

/** True when `code` is a valid state/province code for `country`. */
export function isValidRegion(country: string | null | undefined, code: string | null | undefined) {
  const entry = getRegionsForCountry(country);
  return !!entry && !!code && entry.regions.some((r) => r.code === code);
}
